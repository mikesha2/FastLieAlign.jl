"""
    FastLieAlign

Julia implementation of the optimal-alignment method of

    Congzhou M Sha, "Optimal alignment of Lorentz orientation and
    generalization to matrix Lie groups" (arXiv:2506.14994), now
    expanded to arbitrary matrix Lie groups ("Vector alignment in matrix
    Lie groups").

Given corresponding vectors {v_{A,i}} measured in frame A and {v_{B,i}}
measured in frame B, sharing a common origin, we seek the group element
Λ ∈ G (a matrix Lie group) such that Λ v_{A,i} ≈ v_{B,i}.

The "Lie algebra method" (Method 2 in the paper) generalizes to *any*
matrix Lie group:

  1. Λ₀ = Y X⁺            (unconstrained least-squares, Moore–Penrose)
  2. l₀ = log Λ₀          (matrix logarithm)
  3. l  = proj_𝔤(l₀)      (orthogonal Frobenius projection onto the algebra)
  4. Λ  = exp l           (matrix exponential)

X (resp. Y) stacks the v_{A,i} (resp. v_{B,i}) as columns.

The only group-specific ingredient is the linear projection proj_𝔤 onto
the Lie algebra 𝔤 ⊂ gl(n). Each classical group below provides one.
"""
module FastLieAlign

using LinearAlgebra
using ReverseDiff
using ForwardDiff

export LieGroup,
    GeneralLinear, SpecialLinear, Orthogonal, Unitary,
