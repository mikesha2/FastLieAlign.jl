"Random element of the Lie algebra 𝔤 of `G`, scaled by `scale`."
function random_algebra(G::LieGroup; scale = 1.0, rng = nothing)
    n = matsize(G)
    rn() = rng === nothing ? randn(n, n) : randn(rng, n, n)
    M = eltype_of(G) <: Complex ? scale * (rn() + im * rn()) : scale * rn()
    return algebra_projection(G, M)
end

"Random element of (the identity component of) the group `G` via exp."
random_group(G::LieGroup; scale = 0.3, rng = nothing) = exp(random_algebra(G; scale, rng))

identity_element(G::LieGroup) = Matrix{eltype_of(G)}(I, matsize(G), matsize(G))

