"Adjoint of `A` with respect to the form preserved by `G` (`nothing` when `G` preserves no form)."
form_adjoint(::Orthogonal, A) = transpose(A)
form_adjoint(::Unitary, A) = A'
form_adjoint(G::IndefiniteOrthogonal, A) = (η = metric(G); η * transpose(A) * η)
form_adjoint(G::Symplectic, A) = (J = symplectic_form(G); -J * transpose(A) * J)   # J⁻¹ Aᵀ J with J⁻¹ = -J
form_adjoint(G::IndefiniteUnitary, A) = (η = metric(G); η * A' * η)
form_adjoint(::LieGroup, A) = nothing

"True when λ lies strictly within the angle `wedge` of the negative real axis, by default the open left\nhalf plane (`wedge = π/2`), so that `I - 2P` is the matrix sign function of `g0`."
isnegreal(λ; wedge = π / 2) = abs(angle(λ)) > π - wedge

"Matrix `M` of the form preserved by `G` (`nothing` when `G` preserves no form)."
form_matrix(G::Orthogonal) = Matrix(1.0I, G.n, G.n)
form_matrix(G::Unitary) = Matrix(1.0I, G.n, G.n)
form_matrix(G::IndefiniteOrthogonal) = Matrix(metric(G))
form_matrix(G::Symplectic) = Matrix(symplectic_form(G))
form_matrix(G::IndefiniteUnitary) = Matrix(metric(G))
# whether the form is sesquilinear (⋆ = †) rather than bilinear (⋆ = ᵀ)
sesquilinear(G::LieGroup) = G isa Unitary || G isa IndefiniteUnitary || (eltype_of(G) <: Complex && form_matrix(G) === nothing)
form_matrix(::LieGroup) = nothing

"""
    negative_involution(G, g0) -> r

Algorithm 3 of the manuscript for the groups other than `SL(n, ℂ)` and `SU(n)`. The involution `r = I - 2P` which negates the eigenvalues of `g0` in the open left half
plane, so that `r` is the matrix sign function of `g0` and `r⁻¹ g0` has no negative real
eigenvalue. For the groups preserving a form, `P` is the projector onto the invariant
subspace `N` of those eigenvalues which is orthogonal with respect to the form,
`P = Q (Q⋆ M Q)⁻¹ Q⋆ M` with `Q` a basis of `N` from the ordered Schur form, so that `r`
is the reflection across `N` for the form and lies in the group exactly, also under noise;
it coincides with the spectral projector when `g0` is in the group. For the groups preserving
no form (`GL(n, F)`, `SL(n, ℝ)`) the same formula is used with `M = I`, so `r = I - 2 Q Q⋆` is a
unitary (real orthogonal) reflection which, in the Schur basis, negates exactly the eigenvalues
of `N`. For the Euclidean groups the construction is applied to the rotation block. Returns the identity
when `g0` has no eigenvalue in the left half plane.
"""
function negative_involution(G::LieGroup, g0::AbstractMatrix)
    T = eltype_of(G); n = size(g0, 1)
    if G isa SpecialEuclidean || G isa Similarity
        m = n - 1
        rR = negative_involution(rotation_group(G), g0[1:m, 1:m])
        r = Matrix{T}(I, n, n); r[1:m, 1:m] .= rR
        return r
    end
    M = form_matrix(G)
    M === nothing && (M = Matrix(1.0I, n, n))      # no form: the unitary reflection I - 2QQ⋆
    F = T <: Real ? schur(Matrix{Float64}(real(g0))) : schur(Matrix{ComplexF64}(g0))
    mask = [isnegreal(λ) for λ in F.values]      # conjugate pairs are selected together
    k = count(mask)
    k == 0 && return Matrix{T}(I, n, n)
    k == n && return -Matrix{T}(I, n, n)
    ordschur!(F, mask)
    Q = F.Z[:, 1:k]                              # basis of the invariant subspace N
    Qs = sesquilinear(G) ? Q' : transpose(Q)
    P = Q * ((Qs * M * Q) \ (Qs * M))            # projector onto N, self-adjoint for the form
    return Matrix{T}(I - 2P)
end

"""
    even_reflection(g0) -> r

Algorithm 3 of the manuscript for `SL(n, ℂ)` and `SU(n)`, the involution of `branch_cut_align` for these groups. Every logarithm of an
element of these groups has trace `2πik`; the principal one has `k = round(Σ arg λ_i / 2π)`,
which need not vanish. Reflecting an eigenvalue `λ_i` through the origin, `λ_i ↦ -λ_i`,
moves its principal argument by `s_i π` with `s_i = +1` for `arg λ_i < 0` and `s_i = -1` for
`arg λ_i > 0`. A set `S` of eigenvalues with `Σ_{i∈S} s_i = -2k` therefore makes the
logarithm traceless; such a set always exists because every argument is smaller than `π` in
size, and `|S|` is automatically even. `S` must contain every negative real eigenvalue
(otherwise the principal logarithm is undefined) and no positive real one (the reflection
would put it on the cut); both are enforced by the cost `π(π - 2|arg λ_i|)` of a flip, the
change of `Σ|log λ|²`, which the selection minimizes. The reflection `r = I - 2 Q₁ Q₁ᴴ`
through the invariant subspace spanned by the Schur vectors of `S` is unitary with
`det r = (-1)^{|S|} = 1`, so it lies in `SU(n) ⊂ SL(n, ℂ)`, and `r g0` has the eigenvalues of
`g0` with those in `S` negated. Repeated eigenvalues and Jordan blocks need no special
treatment, since any leading set of Schur vectors spans an invariant subspace.
"""
function even_reflection(g0::AbstractMatrix)
    n = size(g0, 1)
    F = schur(Matrix{ComplexF64}(g0))
    θ = angle.(F.values)
    k = round(Int, sum(θ) / (2π))
    neg = sort([i for i in 1:n if θ[i] < 0]; by = i -> -abs(θ[i]))   # s_i = +1, largest |θ| first
    pos = sort([i for i in 1:n if θ[i] > 0]; by = i -> -abs(θ[i]))   # s_i = -1, largest |θ| first
    cost(i) = π * (π - 2abs(θ[i]))
    cneg = cumsum([cost(i) for i in neg]); cpos = cumsum([cost(i) for i in pos])
    best = nothing
    for a in 0:length(neg)                       # a flips from `neg`, b from `pos`, a - b = -2k
        b = a + 2k
        0 <= b <= length(pos) || continue
        c = (a == 0 ? 0.0 : cneg[a]) + (b == 0 ? 0.0 : cpos[b])
        (best === nothing || c < best[1]) && (best = (c, a, b))
    end
    best === nothing && throw(DomainError(g0, "no admissible set of eigenvalues to reflect"))
    S = vcat(neg[1:best[2]], pos[1:best[3]])
    isempty(S) && return Matrix{ComplexF64}(I, n, n)
    sel = falses(n); sel[S] .= true
    Fo = ordschur(F, sel)
    Q1 = Fo.Z[:, 1:length(S)]
    return Matrix(I - 2 * Q1 * Q1')
end

"""
    spin_align(G::Spin, X, Y) -> Λ

Algorithm 4 of the manuscript, the branch-cut aware method for `Spin(n)`. The rotation
`R₀ =` [`spin_covering`](@ref)`(g0)` covered by `g0 = Y X⁺` is factored as `r_R exp(A)` by the
`SO(n)` case of [`branch_cut_align`](@ref); the lifts `r̃ =` [`spin_lift_involution`](@ref)`(r_R)`
and `B =` [`spin_lift`](@ref)`(A)` give the two elements `±r̃ exp(B)` of `Spin(n)` covering it,
the data choose the sign `ζ`, and the output is `ζ r̃ exp(B + proj log(exp(-B) r̃⁻¹ ζ g0))`,
the projected logarithm of `g0` on the sheet of `B`.
"""
function spin_align(G::Union{Spin,Pin}, X::AbstractMatrix, Y::AbstractMatrix)
    Xm = Matrix(X); Ym = Matrix(Y)
    g0 = Ym * pinv(Xm)
    r, B = spin_lift_group(G, spin_covering(G, g0))
    h = r * exp(B)
    ζ = fro_dot(h * Xm, Ym) >= 0 ? 1 : -1              # the central sign, from the data
    g1 = exp(-B) * (r \ (ζ * g0))                       # ≈ I: g0 on the sheet of B
    return ζ * r * exp(B + algebra_projection(G, log(g1)))
end

"""
    branch_cut_align(G, X, Y) -> Λ

Algorithm 2 of the manuscript, the Lie algebra method extended to the whole group. With
`g0 = Y X⁺` it returns `r exp(proj log(r⁻¹ g0))`, where `r` is the involution of
[`negative_involution`](@ref) for the real groups, the even reflection of
[`even_reflection`](@ref) for `SL(n, ℂ)` and `SU(n)`, which makes the logarithm traceless,
and for `Spin(n)` it calls [`spin_align`](@ref). On noiseless data it returns every element
of the group exactly (Theorem 2.3 of the manuscript).
"""
function branch_cut_align(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix)
    T = eltype_of(G)
    Xm = Matrix(X); Ym = Matrix(Y)
    g0 = Ym * pinv(Xm)
    complex_special = (G isa SpecialLinear && G.field === :complex) || (G isa Unitary && G.special)
    (G isa Spin || G isa Pin) && return spin_align(G, X, Y)
    r = complex_special ? even_reflection(g0) : negative_involution(G, g0)
    g1 = r \ g0                                   # r⁻¹ g0, no negative real eigenvalues
    l0 = log(g1)
    if !(T <: Complex) && eltype(l0) <: Complex
        l0 = real(l0)
    end
    return r * exp(Matrix{T}(algebra_projection(G, l0)))
end

