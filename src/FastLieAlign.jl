"""Abstract supertype for the classical matrix Lie groups."""
abstract type LieGroup end

# Real Frobenius inner product ⟨A,B⟩ = Re tr(A'B); the metric for all the
# orthogonal projections onto Lie algebras (which are real subspaces of gl).
fro_dot(A, B) = real(sum(conj.(A) .* B))

"GL(n, F) — invertible matrices.  field ∈ (:real, :complex)."
struct GeneralLinear <: LieGroup
    n::Int
    field::Symbol
    GeneralLinear(n; field::Symbol = :real) = new(n, field)
end

"SL(n, F) — unit-determinant matrices; algebra = traceless matrices."
struct SpecialLinear <: LieGroup
    n::Int
    field::Symbol
    SpecialLinear(n; field::Symbol = :real) = new(n, field)
end

"O(n) / SO(n), or O(n, ℂ) / SO(n, ℂ) with field = :complex; algebra = antisymmetric matrices."
struct Orthogonal <: LieGroup
    n::Int
    special::Bool
    field::Symbol
    Orthogonal(n; special::Bool = true, field::Symbol = :real) = new(n, special, field)
end

"U(n) / SU(n); algebra = skew-Hermitian (traceless if special)."
struct Unitary <: LieGroup
    n::Int
    special::Bool
    Unitary(n; special::Bool = true) = new(n, special)
end

"O(p, q) / SO(p, q) — metric η = diag(-1ₚ, +1_q); algebra: ηX antisymmetric."
struct IndefiniteOrthogonal <: LieGroup
    p::Int
    q::Int
    special::Bool
    IndefiniteOrthogonal(p, q; special::Bool = true) = new(p, q, special)
end

"Sp(2n, F) with symplectic form J = [0 I; -I 0]; algebra: JX symmetric.  field ∈ (:real, :complex)."
struct Symplectic <: LieGroup
    n::Int     # the matrices are 2n × 2n
    field::Symbol
end
Symplectic(n; field::Symbol = :real) = Symplectic(n, field)

"U(p, q) — the indefinite unitary group of the Hermitian form η = diag(-1ₚ, +1_q); algebra: ηX skew-Hermitian."
struct IndefiniteUnitary <: LieGroup
    p::Int
    q::Int
end

"""
Spin(n) — the simply-connected double cover of SO(n), realized in its
2^⌊n/2⌋-dimensional spinor representation generated by Euclidean gamma matrices.
Its Lie algebra is spanned by the bivectors ½γᵢγⱼ (i<j), a copy of 𝔰𝔬(n).
"""
struct Spin <: LieGroup
    n::Int
end

"""
Pin(n) — the double cover of O(n). It is realized in dimension 2^⌊(n+1)/2⌋ by the generators
`ε_a = i γ_a γ_{n+1}`, `a = 1, …, n`, of a Clifford representation with n+1 generators, which are
Hermitian, anticommute and square to `I`, together with the grading `Γ = γ_{n+1}`, which
anticommutes with every `ε_a`: the even elements of Pin(n) (the subgroup Spin(n)) commute with
`Γ` and the odd ones anticommute. The covering map Pin(n) → O(n) is the twisted adjoint
representation `α(g) ε_b g⁻¹ = Σ_a R_ab ε_a` with `α(g) = Γ g Γ`, under which a unit vector
`ũ = Σ u^a ε_a` covers the reflection `I - 2uuᵀ`. The Lie algebra is 𝔰𝔭𝔦𝔫(n), the span of `ε_a ε_b`.
"""
struct Pin <: LieGroup
    n::Int
end

"The proper orthochronous Lorentz group SO(3,1)₊ from the paper."
Lorentz() = IndefiniteOrthogonal(1, 3; special = true)

"""
SE(p,q) — the special Euclidean / inhomogeneous orthogonal group
SO(p,q) ⋉ ℝ^{p+q}, acting on homogeneous coordinates as the (p+q+1)-square
matrices `[Λ t; 0 1]` with Λ ∈ SO(p,q) and t a translation.
"""
struct SpecialEuclidean <: LieGroup
    p::Int
    q::Int
end

"SE(3,1) — the inhomogeneous Lorentz (Poincaré) group SO(3,1)₊ ⋉ ℝ⁴."
PoincareSE() = SpecialEuclidean(1, 3)

"The linear (rotation/boost) part of a special Euclidean group."
rotation_group(G::SpecialEuclidean) =
    G.p == 0 ? Orthogonal(G.q; special = true) :
    IndefiniteOrthogonal(G.p, G.q; special = true)

"""
Sim(n) — the similarity group ℝ⁺ × SO(n) ⋉ ℝⁿ of scalings, rotations and translations,
acting on homogeneous coordinates as the (n+1)-square matrices `[s R t; 0 1]` with
s > 0 and R ∈ SO(n). Its Lie algebra is the matrices `[c I + a  v; 0 0]` with
a ∈ 𝔰𝔬(n), c ∈ ℝ and v ∈ ℝⁿ.
"""
struct Similarity <: LieGroup
    n::Int
end

"The rotation part SO(n) of a similarity group."
rotation_group(G::Similarity) = Orthogonal(G.n; special = true)

# Size of the square matrices the group acts on.
matsize(G::GeneralLinear) = G.n
matsize(G::SpecialLinear) = G.n
matsize(G::Orthogonal) = G.n
matsize(G::Unitary) = G.n
matsize(G::IndefiniteOrthogonal) = G.p + G.q
matsize(G::Symplectic) = 2G.n
matsize(G::IndefiniteUnitary) = G.p + G.q
matsize(G::SpecialEuclidean) = G.p + G.q + 1
matsize(G::Similarity) = G.n + 1
matsize(G::Spin) = 2^(G.n ÷ 2)
matsize(G::Pin) = 2^((G.n + 1) ÷ 2)

# Element scalar type.
eltype_of(G::GeneralLinear) = G.field === :complex ? ComplexF64 : Float64
eltype_of(G::SpecialLinear) = G.field === :complex ? ComplexF64 : Float64
eltype_of(G::Orthogonal) = G.field === :complex ? ComplexF64 : Float64
eltype_of(::Unitary) = ComplexF64
eltype_of(::IndefiniteOrthogonal) = Float64
eltype_of(G::Symplectic) = G.field === :complex ? ComplexF64 : Float64
eltype_of(::IndefiniteUnitary) = ComplexF64
eltype_of(::SpecialEuclidean) = Float64
eltype_of(::Similarity) = Float64
eltype_of(::Spin) = ComplexF64
eltype_of(::Pin) = ComplexF64

# Minkowski / symplectic structure matrices.
metric(G::IndefiniteOrthogonal) = Diagonal([fill(-1.0, G.p); fill(1.0, G.q)])
metric(G::IndefiniteUnitary) = Diagonal([fill(-1.0, G.p); fill(1.0, G.q)])
function symplectic_form(G::Symplectic)
    n = G.n
    J = zeros(2n, 2n)
    J[1:n, n+1:2n] .= Matrix(I, n, n)
    J[n+1:2n, 1:n] .= -Matrix(I, n, n)
    return J
end

# ---------------------------------------------------------------------------
# Orthogonal (Frobenius) projection onto the Lie algebra 𝔤
# ---------------------------------------------------------------------------

"""
    algebra_projection(G, l₀) -> l

Orthogonal projection (w.r.t. the real Frobenius inner product ⟨A,B⟩ =
Re tr(A'B)) of an arbitrary matrix `l₀` onto the Lie algebra of `G`.
This is the `proj_𝔤` operator of the paper (Eq. 16/17 for the Lorentz case).
"""
function algebra_projection(G::GeneralLinear, l0::AbstractMatrix)
    # 𝔤𝔩(n) is everything; for the real group, drop any imaginary part.
    return G.field === :complex ? Matrix(l0) : real(Matrix(l0))
end

function algebra_projection(G::SpecialLinear, l0::AbstractMatrix)
    l = G.field === :complex ? Matrix(l0) : real(Matrix(l0))
    n = G.n
    return l - (tr(l) / n) * Matrix(I, n, n)
end

# antisymmetric part
function algebra_projection(G::Orthogonal, l0::AbstractMatrix)
    l = G.field === :complex ? Matrix(l0) : real(Matrix(l0))
    return (l - transpose(l)) / 2
end

function algebra_projection(G::Unitary, l0::AbstractMatrix)
    l = (l0 - l0') / 2                      # skew-Hermitian part
    if G.special
        n = G.n
        l -= (tr(l) / n) * Matrix(I, n, n)  # remove (imaginary) trace -> 𝔰𝔲(n)
    end
    return Matrix(l)
end

function algebra_projection(G::IndefiniteOrthogonal, l0::AbstractMatrix)
    # 𝔤 = { X : ηX antisymmetric }.  Since η is an isometry, projecting X is
    # equivalent to projecting ηX onto antisymmetric matrices:
    #     l = ½ (l₀ - η l₀ᵀ η).
    η = metric(G)
    l = real(Matrix(l0))
    return (l - η * transpose(l) * η) / 2
end

function algebra_projection(G::Symplectic, l0::AbstractMatrix)
    # 𝔤 = { X : JX symmetric }.  J is orthogonal, so projecting X is
    # equivalent to projecting JX onto symmetric matrices:
    #     l = ½ (l₀ + Jᵀ l₀ᵀ Jᵀ).
    J = symplectic_form(G)
    l = G.field === :complex ? Matrix(l0) : real(Matrix(l0))
    return (l + transpose(J) * transpose(l) * transpose(J)) / 2
end

function algebra_projection(G::IndefiniteUnitary, l0::AbstractMatrix)
    # 𝔤 = { X : ηX skew-Hermitian }:  l = ½ (l₀ - η l₀† η).
    η = metric(G)
    l = Matrix(l0)
    return (l - η * l' * η) / 2
end

# Euclidean gamma matrices {γᵢ, γⱼ} = 2δᵢⱼ in 2^⌊n/2⌋ dimensions, built by the
# Jordan–Wigner tensor construction.  Cached per n.
const _GAMMA_CACHE = Dict{Int,Vector{Matrix{ComplexF64}}}()
function gamma_matrices(n::Int)
    haskey(_GAMMA_CACHE, n) && return _GAMMA_CACHE[n]
    σx = ComplexF64[0 1; 1 0]; σy = ComplexF64[0 -im; im 0]
    σz = ComplexF64[1 0; 0 -1]; I2 = Matrix{ComplexF64}(I, 2, 2)
    k = n ÷ 2
    kron_chain(ops) = foldl(kron, ops)
    γ = Matrix{ComplexF64}[]
    for a in 1:k
        pre = [σz for _ in 1:a-1]; post = [I2 for _ in 1:k-a]
        push!(γ, kron_chain([pre; [σx]; post]))
        push!(γ, kron_chain([pre; [σy]; post]))
    end
    isodd(n) && push!(γ, kron_chain([σz for _ in 1:k]))   # chirality element
    _GAMMA_CACHE[n] = γ
    return γ
end

# Generators of the Clifford representation used for Spin(n) and Pin(n), and the grading
# automorphism α of the Clifford algebra (the identity on Spin(n), conjugation by Γ = γ_{n+1}
# on Pin(n)), which enters the covering map as the twisted adjoint representation.
clifford_generators(G::Spin) = gamma_matrices(G.n)
const _PIN_GEN_CACHE = Dict{Int,Vector{Matrix{ComplexF64}}}()
function clifford_generators(G::Pin)
    haskey(_PIN_GEN_CACHE, G.n) && return _PIN_GEN_CACHE[G.n]
    γ = gamma_matrices(G.n + 1)
    ε = [im .* (γ[a] * γ[G.n+1]) for a in 1:G.n]
    _PIN_GEN_CACHE[G.n] = ε
    return ε
end
pin_grading(G::Pin) = gamma_matrices(G.n + 1)[G.n+1]
grading_twist(::Spin, g) = g
grading_twist(G::Pin, g) = (Γ = pin_grading(G); Γ * g * Γ)

# Orthonormal (real-Frobenius) basis of the spin algebra: span{ ½γᵢγⱼ, i<j }.
const _SPIN_BASIS_CACHE = Dict{Tuple{Symbol,Int},Vector{Matrix{ComplexF64}}}()
function spin_basis(G::Union{Spin,Pin})
    key = (nameof(typeof(G)), G.n); n = G.n
    haskey(_SPIN_BASIS_CACHE, key) && return _SPIN_BASIS_CACHE[key]
    γ = clifford_generators(G)
    onb = Matrix{ComplexF64}[]
    for i in 1:n, j in i+1:n
        v = γ[i] * γ[j] / 2
        for b in onb
            v -= fro_dot(b, v) * b
        end
        nv = sqrt(fro_dot(v, v))
        nv > 1e-9 && push!(onb, v / nv)
    end
    _SPIN_BASIS_CACHE[key] = onb
    return onb
end

function algebra_projection(G::Union{Spin,Pin}, l0::AbstractMatrix)
    # Project onto the real span of the bivector generators (an 𝔰𝔬(n) copy).
    onb = spin_basis(G)
    out = zeros(ComplexF64, size(l0))
    for b in onb
        out .+= fro_dot(b, l0) .* b
    end
    return out
end

"""
    spin_covering(G::Spin, g) -> R

The covering map `Spin(n) → SO(n)`: `g γ_b g⁻¹ = Σ_a R_ab γ_a`, so `R_ab = tr(γ_a g γ_b g⁻¹)/d`.
For `Pin(n)` it is the twisted adjoint representation `α(g) ε_b g⁻¹ = Σ_a R_ab ε_a` onto `O(n)`,
with `α(g) = Γ g Γ`. For `g` outside the group it returns the matrix of these traces, which is
close to an orthogonal matrix when `g` is close to the group.
"""
function spin_covering(G::Union{Spin,Pin}, g::AbstractMatrix)
    γ = clifford_generators(G); n = G.n; d = size(g, 1)
    gm = Matrix{ComplexF64}(g); gi = inv(gm); ga = grading_twist(G, gm)
    R = zeros(n, n)
    for b in 1:n
        M = ga * γ[b] * gi
        for a in 1:n
            R[a, b] = real(sum(transpose(γ[a]) .* M)) / d     # tr(γ_a M)
        end
    end
    return R
end

"""
    spin_lift(G::Spin, A) -> B

The lift of `A ∈ 𝔰𝔬(n)` to the bivector `B = ¼ Σ_ab A_ab γ_a γ_b ∈ 𝔰𝔭𝔦𝔫(n)`, so that
`exp(B)` covers `exp(A)`.
"""
function spin_lift(G::Union{Spin,Pin}, A::AbstractMatrix)
    γ = clifford_generators(G); n = G.n
    B = zeros(ComplexF64, size(γ[1]))
    for a in 1:n, b in a+1:n
        B .+= ((A[a, b] - A[b, a]) / 4) .* (γ[a] * γ[b])
    end
    return B
end

"""
    spin_lift_involution(G::Spin, rR) -> r̃

A lift of the involution `rR = I - 2P ∈ O(n)`, the reflection of the `k`-dimensional subspace
`N = range(P)`: with `u_1, …, u_k` an orthonormal basis of `N` and `ũ = Σ_a u^a γ_a`, the lift is
`ũ_1 ũ_2 ⋯ ũ_k`, which lies in `Spin(n)` for even `k` (where it is `Π_j exp(π ũ_{2j-1} ũ_{2j} / 2)`)
and in the odd component of `Pin(n)` for odd `k`. The other lift is its negative.
"""
function spin_lift_involution(G::Union{Spin,Pin}, rR::AbstractMatrix)
    γ = clifford_generators(G); n = G.n; d = size(γ[1], 1)
    E = eigen(Symmetric(Matrix((rR + rR') / 2)))
    U = E.vectors[:, E.values .< 0]
    (G isa Pin || iseven(size(U, 2))) || throw(DomainError(rR, "the -1 eigenspace of an element of SO(n) has even dimension"))
    r = Matrix{ComplexF64}(I, d, d)
    for j in 1:size(U, 2)
        r = r * sum(U[a, j] .* γ[a] for a in 1:n)
    end
    return r
end

# One of the two elements of Spin(n) covering R ∈ SO(n): the lift of the involution of R
# times the exponential of the lift of the projected logarithm of the rest.
function spin_lift_group(G::Union{Spin,Pin}, R::AbstractMatrix)
    SO = Orthogonal(G.n; special = G isa Spin)
    rR = negative_involution(SO, R)
    A = algebra_projection(SO, real(log(rR \ R)))
    return spin_lift_involution(G, rR), spin_lift(G, A)
end

function algebra_projection(G::SpecialEuclidean, l0::AbstractMatrix)
    # 𝔰𝔢(p,q) = { [a v; 0 0] : a ∈ 𝔰𝔬(p,q), v ∈ ℝ^{p+q} }.  These blocks are
    # mutually orthogonal, so project blockwise: rotation part onto 𝔰𝔬(p,q),
    # keep the translation column, zero the bottom row.
    n = G.p + G.q
    l = real(Matrix(l0))
    out = zeros(n + 1, n + 1)
    out[1:n, 1:n] = algebra_projection(rotation_group(G), l[1:n, 1:n])
    out[1:n, n+1] = l[1:n, n+1]
    return out
end

function algebra_projection(G::Similarity, l0::AbstractMatrix)
    # 𝔰𝔦𝔪(n) = { [c I + a  v; 0 0] : a ∈ 𝔰𝔬(n), c ∈ ℝ, v ∈ ℝⁿ }.  The block
    # algebra 𝔰𝔬(n) ⊕ ℝ I is an orthogonal sum, so the block is projected to its
    # antisymmetric part plus (tr/n) I; the translation column is kept.
    n = G.n
    l = real(Matrix(l0))
    B = l[1:n, 1:n]
    out = zeros(n + 1, n + 1)
    out[1:n, 1:n] = (B - transpose(B)) / 2 + (tr(B) / n) * I
    out[1:n, n+1] = l[1:n, n+1]
    return out
end

