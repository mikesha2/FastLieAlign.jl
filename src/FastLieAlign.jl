# Membership tests (for verification / tests)
# ---------------------------------------------------------------------------

"True if `X` lies in the Lie algebra of `G` to tolerance `atol`."
function in_algebra(G::LieGroup, X::AbstractMatrix; atol = 1e-8)
    return norm(X - algebra_projection(G, X)) <= atol * max(1, norm(X))
end

"True if `g` lies in (the identity component of) the group `G` to tolerance `atol`."
function in_group(G::GeneralLinear, g; atol = 1e-8)
    return abs(det(g)) > atol
end
in_group(G::SpecialLinear, g; atol = 1e-8) = isapprox(det(g), 1; atol)
in_group(G::Orthogonal, g; atol = 1e-8) =
    isapprox(transpose(g) * g, Matrix(I, G.n, G.n); atol) && (!G.special || isapprox(det(g), 1; atol))
in_group(G::Unitary, g; atol = 1e-8) =
    isapprox(g'g, Matrix(I, G.n, G.n); atol) && (!G.special || isapprox(det(g), 1; atol))
function in_group(G::IndefiniteOrthogonal, g; atol = 1e-8)
    η = metric(G)
    return isapprox(transpose(g) * η * g, η; atol)
end
function in_group(G::Symplectic, g; atol = 1e-8)
    J = symplectic_form(G)
    return isapprox(transpose(g) * J * g, J; atol)
end
function in_group(G::IndefiniteUnitary, g; atol = 1e-8)
    η = metric(G)
    return isapprox(g' * η * g, η; atol)
end
function in_group(G::SpecialEuclidean, g; atol = 1e-8)
    n = G.p + G.q
    bottom = vcat(zeros(n), 1.0)
    return in_group(rotation_group(G), g[1:n, 1:n]; atol) &&
           isapprox(g[n+1, :], bottom; atol)
end
function in_group(G::Similarity, g; atol = 1e-8)
    n = G.n
    A = g[1:n, 1:n]
    s = sqrt(tr(transpose(A) * A) / n)            # the scale, for A = s R with R orthogonal
    bottom = vcat(zeros(n), 1.0)
    return s > 0 && in_group(rotation_group(G), A / s; atol) &&
           isapprox(g[n+1, :], bottom; atol)
end
function in_group(G::Union{Spin,Pin}, g; atol = 1e-8)
    N = matsize(G); γ = clifford_generators(G)
    isapprox(g'g, Matrix(I, N, N); atol) || return false   # unitary
    ga = grading_twist(G, Matrix{ComplexF64}(g))
    (G isa Spin || isapprox(ga, g; atol) || isapprox(ga, -g; atol)) || return false   # definite parity
    R = spin_covering(G, g)                                 # α(g) γ_b g⁻¹ = Σ_a R_ab γ_a ...
    gi = inv(Matrix{ComplexF64}(g))
    for b in 1:G.n                                          # ... with R exactly orthogonal
        isapprox(ga * γ[b] * gi, sum(R[a, b] .* γ[a] for a in 1:G.n); atol) || return false
    end
    (isapprox(R'R, I; atol) && (G isa Pin || det(R) > 0)) || return false
    r, B = spin_lift_group(G, R)                            # g is one of the two lifts of R
    h = r * exp(B)
    return min(norm(g - h), norm(g + h)) <= atol * max(1, norm(h))
end

