# The alignment method
# ---------------------------------------------------------------------------

"""
    naive_align(G, X, Y) -> Λ

Lie algebra alignment method.  `X` and `Y` are `n × m` matrices whose columns
are the corresponding vectors v_{A,i} and v_{B,i}.  Returns the estimated
group element `Λ ∈ G` minimizing ‖Λ X − Y‖ subject to Λ ∈ G (to leading order).
"""
function naive_align(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix)
    Λ0 = Y * pinv(Matrix(X))     # step 1: unconstrained least squares
    l0 = log(Λ0)                 # step 2: matrix logarithm (principal branch)
    if !(eltype_of(G) <: Complex) && eltype(l0) <: Complex
        maximum(abs, imag(l0)) > 1e-8 * max(1.0, norm(l0)) && throw(DomainError(Λ0,
            "the least squares matrix has a negative real eigenvalue, so it has no real logarithm; " *
            "the method is not defined here (Remark on failure cases in the paper). " *
            "If the group has several components, use align_components."))
        l0 = real(l0)
    end
    l = algebra_projection(G, l0)  # step 3: project onto 𝔤
    return exp(Matrix{eltype_of(G)}(l))   # step 4: back to the group
end

"""
    component_representatives(G) -> Vector{Matrix}

One representative of each connected component of `G`, the identity first.
`Orthogonal(n; special=false)` and real `GeneralLinear(n)` have two components
(sign of the determinant); `IndefiniteOrthogonal(p, q; special=false)` has four
(signs of `det g` and of the determinant of the upper left `p×p` block); the
connected groups have one.
"""
function component_representatives(G::LieGroup)
    n = matsize(G); I_n = Matrix{Float64}(I, n, n)
    refl(i) = (R = copy(I_n); R[i, i] = -1.0; R)
    if G isa Pin
        return [Matrix{ComplexF64}(I, n, n), clifford_generators(G)[1]]
    elseif (G isa Orthogonal && !G.special) || (G isa GeneralLinear && G.field === :real)
        return [I_n, refl(1)]
    elseif G isa IndefiniteOrthogonal && !G.special
        return [I_n, refl(1), refl(G.p + 1), refl(1) * refl(G.p + 1)]
    else
        return [I_n]
    end
end

"""
    align_components(G, X, Y; all = false) -> Λ

The Lie algebra method on a group with several connected components.  Each
component is a coset `h G⁰`, so the method is applied to `(X, h⁻¹Y)` for a
representative `h` of the component and the result is `h Λ'`.  By default the
component is read off the signs of `det g₀` and, for `O(p,q)`, of the upper left
block of `g₀ = Y X⁺`, which is reliable when the noise is small; with
`all = true` every representative is tried and the candidate with the smallest
residual `‖ΛX − Y‖` is returned.
"""
function align_components(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix; all::Bool = false)
    reps = component_representatives(G)
    length(reps) == 1 && return naive_align(G, X, Y)
    Xm = Matrix(X); Ym = Matrix(Y)
    g0 = Ym * pinv(Xm)
    p = G isa IndefiniteOrthogonal ? G.p : 0
    invariants(g) = (sign(det(g)), p == 0 ? 1.0 : sign(det(g[1:p, 1:p])))
    best = nothing
    for h in reps
        (all || invariants(h) == invariants(g0)) || continue
        Λ = try h * naive_align(G, Xm, h \ Ym) catch e; e isa DomainError ? continue : rethrow() end
        r = norm(Λ * Xm - Ym)
        (best === nothing || r < best[2]) && (best = (Λ, r))
    end
    best === nothing && throw(DomainError(g0, "no component gives a real logarithm"))
    return best[1]
end

"""
    gauss_newton_refine(G, X, Y; iters=12, tol=1e-13) -> Λ

Data-covariance correction of [`naive_align`](@ref).  The closed-form estimate
minimizes the alignment objective only to leading order, because step 3 of
[`naive_align`](@ref) projects in the algebra under the flat Frobenius metric whereas
`‖gX − Y‖²` weights directions by the data covariance `S = XX†`
(see the error analysis in the paper).  The constrained optimum solves the
data-weighted normal equations `G c = b` with
`G_kj = ⟨Bₖ ΛX, Bⱼ ΛX⟩` and `b_k = ⟨Bₖ ΛX, R⟩`, `R = Y − ΛX`; i.e. the
correction `δl = Σ cₖ Bₖ ∈ 𝔤` is the pseudoinverse solution
`c = D⁺ vec(R)` of the design `D = [vec(B₁ ΛX) … vec(B_d ΛX)]` (real and
imaginary parts stacked for complex groups).  Applying `Λ ← exp(δl) Λ ∈ G` and
repeating once or twice to absorb the nonlinearity of `exp` reaches the
constrained least-squares optimum of [`align_direct`](@ref)/[`align_newton`](@ref)
at the cost of one extra pseudoinverse, with no nonlinear optimizer.  On
noiseless data `R = 0`, so `c = 0` and the correction is inactive.
"""
function gauss_newton_refine(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix;
                         iters = 12, tol = 1e-13, init = nothing)
    T = eltype_of(G)
    basis = algebra_basis(G); d = length(basis)
    d == 0 && return identity_element(G)
    Λ = init === nothing ? naive_align(G, X, Y) : Matrix{T}(init)
    Xm = Matrix(X); Ym = Matrix(Y)
    cplx = T <: Complex
    for _ in 1:iters
        ΛX = Λ * Xm
        R = Ym .- ΛX                                  # residual
        # Data-weighted normal equations G c = b in the algebra basis: the
        # pseudoinverse of the design D = [vec(Bₖ ΛX)] against vec(R).  This is
        # the projection onto 𝔤 in the data (S = XX†) metric, not the flat one.
        D = reduce(hcat, (vec(B * ΛX) for B in basis))
        r = vec(R)
        c = cplx ? [real(D); imag(D)] \ [real(r); imag(r)] :     # least squares by QR
                   real(D) \ real(r)
        δl = sum(c[k] .* basis[k] for k in 1:d)
        norm(δl) <= tol * max(1.0, norm(Λ)) && break
        Λ = exp(Matrix{T}(δl)) * Λ                    # multiplicative, stays in G
    end
    return Λ
end

# ---------------------------------------------------------------------------
# Special Euclidean alignment: aligning *points* p_{B,i} = Λ p_{A,i} + t.
# ---------------------------------------------------------------------------

"Augment an n×m matrix of points to (n+1)×m homogeneous coordinates."
homogenize(P) = vcat(Matrix(P), ones(1, size(P, 2)))

"""
    align_se(G, PA, PB) -> M

Special Euclidean alignment via the Lie algebra method.  `PA`, `PB` are
`(p+q)×m` matrices of corresponding points related by `p_{B,i} = Λ p_{A,i} + t`.
Lifts the points to homogeneous coordinates and applies [`naive_align`](@ref) on the
full group `G = SpecialEuclidean(p,q)`, jointly recovering rotation/boost *and*
translation as a single `(p+q+1)`-square element `[Λ t; 0 1]`.
"""
function align_se(G::SpecialEuclidean, PA::AbstractMatrix, PB::AbstractMatrix)
    return naive_align(G, homogenize(PA), homogenize(PB))
end

"""
    align_se_centroid(G, PA, PB) -> M

Traditional decoupled alignment (the classical Kabsch/Procrustes recipe for
rigid motions): center each point set on its centroid, solve for the optimal
linear part Λ ∈ SO(p,q) on the centered vectors, then recover the translation
`t = c_B − Λ c_A` from the centroids.  Returned as `[Λ t; 0 1]`.

Centering is exact: if `p_{B,i} = Λ p_{A,i} + t` then the centered vectors
satisfy `q_{B,i} = Λ q_{A,i}` (the translation cancels), so this agrees with
[`align_se`](@ref) in the noiseless case.
"""
function align_se_centroid(G::SpecialEuclidean, PA::AbstractMatrix, PB::AbstractMatrix)
    n = G.p + G.q
    m = size(PA, 2)
    cA = vec(sum(PA, dims = 2)) ./ m
    cB = vec(sum(PB, dims = 2)) ./ m
    QA = Matrix(PA) .- cA          # center on centroids
    QB = Matrix(PB) .- cB
    Λ = naive_align(rotation_group(G), QA, QB)   # optimal linear part on centered data
    t = cB - Λ * cA                # recover translation from centroids
    M = zeros(n + 1, n + 1)
    M[1:n, 1:n] = Λ
    M[1:n, n+1] = t
    M[n+1, n+1] = 1
    return M
end

# ---------------------------------------------------------------------------
# Method 1: direct nonlinear optimization (paper's first method, generalized)
#
# Parametrize the group through real coordinates on its Lie algebra,
# Λ(θ) = exp(Σ θₖ Bₖ) with {Bₖ} an orthonormal basis of 𝔤, and minimize the
# least-squares objective f(θ) = ‖Λ(θ)X − Y‖² starting from the identity
# (θ = 0).  Optimization uses a self-contained BFGS with Armijo backtracking
# (no external optimizer); the gradient is obtained by reverse-mode automatic
# differentiation (ReverseDiff.jl) through a traceable Taylor matrix exponential.
#
# ReverseDiff only tracks real arrays, so complex groups are embedded into real
# 2n×2n matrices via the ring homomorphism φ(M) = [Re M  −Im M; Im M  Re M],
# which satisfies φ(AB)=φ(A)φ(B) and hence exp(φ(M)) = φ(exp M).
# ---------------------------------------------------------------------------

# Matrix exponential as a fixed-schedule scaling-and-squaring Taylor series.
# The schedule is data-independent (no branches on the input), so a single
# ReverseDiff tape recorded at θ = 0 stays valid for every θ in the search.
# For ‖A‖ ≲ 16 the truncation error is at machine precision.
function expm_taylor(A::AbstractMatrix; squarings::Int = 5, order::Int = 12)
    n = size(A, 1)
    B = A ./ (2.0^squarings)
    Id = Matrix{Float64}(I, n, n)
    E = Id .+ B
    term = B
    for k in 2:order
        term = (term * B) ./ k
        E = E .+ term
    end
    for _ in 1:squarings
        E = E * E
    end
    return E
end

"""
    algebra_basis(G) -> Vector{Matrix}

Orthonormal (real Frobenius) basis of the Lie algebra 𝔤, obtained by projecting
the standard matrix units onto 𝔤 and Gram–Schmidt orthonormalizing.  For complex
groups the algebra is treated as a real vector space (units `Eᵢⱼ` and `i·Eᵢⱼ`).
The length of the basis is the real dimension of the group.
"""
function algebra_basis(G::LieGroup)
    n = matsize(G)
    cplx = eltype_of(G) <: Complex
    cands = Matrix{ComplexF64}[]
    for i in 1:n, j in 1:n
        E = zeros(ComplexF64, n, n); E[i, j] = 1
        push!(cands, ComplexF64.(algebra_projection(G, E)))
        if cplx
            E2 = zeros(ComplexF64, n, n); E2[i, j] = im
            push!(cands, ComplexF64.(algebra_projection(G, E2)))
        end
    end
    basis = Matrix{ComplexF64}[]
    for M in cands
        v = copy(M)
        for b in basis
            v -= fro_dot(b, v) * b
        end
        nv = sqrt(fro_dot(v, v))
        nv > 1e-9 && push!(basis, v / nv)
    end
    return cplx ? basis : [real(b) for b in basis]
end

# Compact BFGS with Armijo backtracking line search.  `grad!(g, x)` fills the
# gradient in place (here supplied by ReverseDiff).
function _bfgs(f, grad!, x0; maxiter = 500, gtol = 1e-12)
    x = copy(x0); m = length(x)
    isempty(x) && return x
    H = Matrix{Float64}(I, m, m)
    g = similar(x); grad!(g, x)
    for _ in 1:maxiter
        norm(g) < gtol && break
        p = -H * g
        gp = dot(g, p)
        gp >= 0 && (p = -g; gp = dot(g, p))   # reset to steepest descent
        α = 1.0; fx = f(x)
        while α > 1e-14 && !(f(x .+ α .* p) <= fx + 1e-4 * α * gp)
            α /= 2          # `!(... <= ...)` also rejects Inf/NaN trial values
        end
        s = α .* p; xnew = x .+ s
        gnew = similar(x); grad!(gnew, xnew); y = gnew .- g
        # A noncompact (boost) direction can overshoot into an overflowing
        # exponential; stop at the last finite iterate rather than propagate NaN.
        (all(isfinite, xnew) && all(isfinite, gnew)) || break
        sy = dot(s, y)
        if sy > 1e-12          # BFGS curvature condition
            ρ = 1 / sy
            Im = Matrix{Float64}(I, m, m)
            H = (Im .- ρ .* (s * y')) * H * (Im .- ρ .* (y * s')) .+ ρ .* (s * s')
        end
        x = xnew; g = gnew
    end
    return x
end

# Damped Newton's method in optimization (Wikipedia: "Newton's method in
# optimization").  Each step solves the Newton system `H Δ = g` for the
# update `x ← x − Δ`, with the Hessian `H` obtained by central differencing
# the (AD) gradient.  `H` is symmetrized; if the pure Newton step (λ = 0)
# fails to decrease `f`, a Levenberg-style damping `H + λI` is grown until it
# does, which keeps the iteration well-defined when `H` is indefinite (the
# objective is nonconvex away from the optimum).
function _newton(f, grad!, x0; maxiter = 100, gtol = 1e-12, h = 1e-6)
    x = copy(x0); d = length(x)
    isempty(x) && return x
    g = similar(x); grad!(g, x); fx = f(x)
    gp = similar(x); gm = similar(x); H = zeros(d, d)
    for _ in 1:maxiter
        norm(g) < gtol && break
        for j in 1:d
            xj = x[j]
            x[j] = xj + h; grad!(gp, x)
            x[j] = xj - h; grad!(gm, x)
            x[j] = xj
            @views H[:, j] .= (gp .- gm) ./ (2h)
        end
        H .= (H .+ H') ./ 2
        λ = 0.0; stepped = false
        for _try in 1:40
            Δ = try
                (H + λ * I) \ g
            catch
                fill(NaN, d)
            end
            if all(isfinite, Δ)
                xnew = x .- Δ
                fnew = f(xnew)
                if isfinite(fnew) && fnew < fx
                    x .= xnew; fx = fnew; grad!(g, x); stepped = true; break
                end
            end
            λ = λ == 0.0 ? 1e-8 : λ * 10
        end
        stepped || break
    end
    return x
end

# Shared setup for the direct optimizers: returns the real-embedded objective
# `f(θ) = ‖exp(Σθₖ B̃ₖ) X̃ − Ỹ‖²`, the basis, and a reconstructor that maps the
# optimized coordinates back to a group element Λ = exp(Σθₖ Bₖ) ∈ G.
function _direct_problem(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix)
    basis = algebra_basis(G)
    d = length(basis)
    cplx = eltype_of(G) <: Complex
    embed(M) = [real(M) -imag(M); imag(M) real(M)]
    B̃ = cplx ? [embed(b) for b in basis] : [real(b) for b in basis]
    Xr = cplx ? [real(Matrix(X)); imag(Matrix(X))] : real(Matrix(X))
    Yr = cplx ? [real(Matrix(Y)); imag(Matrix(Y))] : real(Matrix(Y))
    function f(θ)
        A = θ[1] .* B̃[1]
        for k in 2:d
            A = A .+ θ[k] .* B̃[k]
        end
        return sum(abs2, expm_taylor(A) * Xr .- Yr)
    end
    function makeΛ(θ)
        A = θ[1] .* basis[1]
        for k in 2:d
            A = A .+ θ[k] .* basis[k]
        end
        Λ = exp(Matrix{eltype_of(G)}(A))
        return cplx ? Λ : real(Λ)
    end
    return f, basis, d, makeΛ
end

"""
    align_newton(G, X, Y; maxiter=100) -> Λ

Direct nonlinear optimization by Newton's method in optimization, started from
the identity (θ = 0).  Like [`align_direct`](@ref) it minimizes ‖Λ(θ)X − Y‖²
over Lie-algebra coordinates θ, but updates θ with damped Newton steps (Hessian
from central-differenced ReverseDiff gradients) rather than BFGS.  Returns
Λ = exp(Σ θₖ Bₖ) ∈ G.
"""
function align_newton(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix;
                      maxiter = 100, init = nothing)
    f, basis, d, makeΛ = _direct_problem(G, X, Y)
    d == 0 && return identity_element(G)
    θ0 = if init === nothing
        zeros(d)                                   # start from the identity
    else
        # Warm-start at the group element `init`: its algebra coordinates are
        # θ_k = ⟨B_k, l⟩ with l = proj_𝔤(log init) in the orthonormal basis.
        l = algebra_projection(G, log(Matrix{ComplexF64}(init)))
        [real(dot(basis[k], l)) for k in 1:d]
    end
    tape = ReverseDiff.compile(ReverseDiff.GradientTape(f, θ0))
    grad!(g, θ) = ReverseDiff.gradient!(g, tape, θ)
    θ = _newton(f, grad!, θ0; maxiter)
    return makeΛ(θ)
end

# Damped Newton with an explicit (full) Hessian function, mirroring `_newton`
# but taking `hess(x)` instead of central-differencing the gradient.
function _newton_full(f, grad, hess, x0; maxiter = 100, gtol = 1e-12)
    x = copy(x0); d = length(x)
    isempty(x) && return x
    g = grad(x); fx = f(x)
    for _ in 1:maxiter
        norm(g) < gtol && break
        H = hess(x); H = (H .+ H') ./ 2
        λ = 0.0; stepped = false
        for _try in 1:40
            Δ = try
                (H + λ * I) \ g
            catch
                fill(NaN, d)
            end
            if all(isfinite, Δ)
                xnew = x .- Δ
                fnew = f(xnew)
                if isfinite(fnew) && fnew < fx
                    x .= xnew; fx = fnew; g = grad(x); stepped = true; break
                end
            end
            λ = λ == 0.0 ? 1e-8 : λ * 10
        end
        stepped || break
    end
    return x
end

"""
    align_newton_full(G, X, Y; maxiter=100, init=nothing) -> Λ

Like [`align_newton`](@ref), but forms the exact Hessian by forward-over-reverse
automatic differentiation (the ForwardDiff Jacobian of the ReverseDiff
gradient) rather than central-differencing the gradient.  With `init` it
warm-starts at the Lie-algebra coordinates of that group element.
"""
function align_newton_full(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix;
                           maxiter = 100, init = nothing)
    f, basis, d, makeΛ = _direct_problem(G, X, Y)
    d == 0 && return identity_element(G)
    θ0 = if init === nothing
        zeros(d)
    else
        l = algebra_projection(G, log(Matrix{ComplexF64}(init)))
        [real(dot(basis[k], l)) for k in 1:d]
    end
    grad(θ) = ReverseDiff.gradient(f, θ)
    hess(θ) = ForwardDiff.jacobian(grad, θ)
    θ = _newton_full(f, grad, hess, θ0; maxiter)
    return makeΛ(θ)
end

"""
    align_direct(G, X, Y; maxiter=500, init=nothing) -> Λ

Direct nonlinear optimization (Method 1 of the paper), generalized to any
classical group.  Minimizes ‖Λ(θ)X − Y‖² over Lie-algebra coordinates θ via
BFGS with reverse-mode AD gradients (ReverseDiff.jl), returning
Λ = exp(Σ θₖ Bₖ) ∈ G.  Slower than [`naive_align`](@ref) but serves as an independent baseline; with
exact gradients the two methods agree (cf. paper Figs. 1–2).  Pass
`init = naive_align(G, X, Y)` to warm-start the BFGS at the closed-form solution.
"""
function align_direct(G::LieGroup, X::AbstractMatrix, Y::AbstractMatrix; maxiter = 1000, init = nothing)
    basis = algebra_basis(G)
    d = length(basis)
    d == 0 && return identity_element(G)
    cplx = eltype_of(G) <: Complex

    # Real representation: embed complex data/algebra via φ (see note above).
    embed(M) = [real(M) -imag(M); imag(M) real(M)]
    B̃ = cplx ? [embed(b) for b in basis] : [real(b) for b in basis]
    Xr = cplx ? [real(Matrix(X)); imag(Matrix(X))] : real(Matrix(X))
    Yr = cplx ? [real(Matrix(Y)); imag(Matrix(Y))] : real(Matrix(Y))

    function f(θ)
        A = θ[1] .* B̃[1]
        for k in 2:d
            A = A .+ θ[k] .* B̃[k]
        end
        return sum(abs2, expm_taylor(A) * Xr .- Yr)
    end

    # Project an arbitrary algebra element onto the basis coordinates.
    function coords(M)
        c = zeros(d)
        for k in 1:d
            c[k] = fro_dot(basis[k], M)
        end
        return c
    end

    θ0 = if init === nothing
        zeros(d)
    else
        # `init` is an algebra element; map it to coordinates θ.
        coords(init)
    end

    tape = ReverseDiff.compile(ReverseDiff.GradientTape(f, θ0))
    grad!(g, θ) = ReverseDiff.gradient!(g, tape, θ)
    θ = _bfgs(f, grad!, θ0; maxiter)

    A = θ[1] .* basis[1]
    for k in 2:d
        A = A .+ θ[k] .* basis[k]
    end
    Λ = exp(Matrix{eltype_of(G)}(A))
    return cplx ? Λ : real(Λ)
end

"""
    align_error(Λ_est, Λ_true) -> (l2, linf)

Frobenius (L²) and max (L∞) element-wise errors between the estimated and
true transformation matrices, as reported in Figs. 1–2 of the paper.
"""
function align_error(Λ_est::AbstractMatrix, Λ_true::AbstractMatrix)
    D = Λ_est - Λ_true
    return (norm(D), maximum(abs, D))
end


